//! Render the catalogue from the actual Definitions loader; no simulation or balance copy.
use sim::{Definitions, ProductionItem, load_ruleset};
use std::{error::Error, fmt::Write, path::PathBuf};

fn arms(d: &Definitions, item: ProductionItem, elite: bool) -> String {
    let terms = match item {
        ProductionItem::Unit(k) => d.unit_combat(k),
        ProductionItem::Building(k) => d.building_combat(k),
    };
    terms
        .map(|t| {
            t.weapons(elite)
                .into_iter()
                .flatten()
                .filter_map(|k| d.weapon(k).map(|w| w.id.as_str()))
                .collect::<Vec<_>>()
                .join(", ")
        })
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| "—".into())
}
fn main() -> Result<(), Box<dyn Error>> {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let d = load_ruleset(root.join("assets/data"))?;
    let mut out = String::from(
        "# Loaded ruleset catalogue\n\nGenerated by `cargo run -p sim --example ra9_catalogue` from the actual Definitions loader. Values are game units: credits, ticks at 20 per second, subcells at 256 per cell. This catalogue does not claim that a parity audit or native validation passed. Source mappings and exact intentional differences are recorded in `crates/sim/tests/reference/`.\n\n## Units\n\n| ID | Cost | HP | Speed | Domain | Role | Base weapons | Elite weapons |\n|---|---:|---:|---:|---|---|---|---|\n",
    );
    for u in d.units() {
        let k = d.unit_kind(&u.id).ok_or("catalogue unit identity")?;
        let item = ProductionItem::Unit(k);
        let m = d.metadata(item).ok_or("catalogue metadata")?;
        let hp = d.unit_combat(k).ok_or("catalogue unit combat")?.hit_points;
        let cost = d.production(item).ok_or("catalogue production")?.cost;
        writeln!(
            &mut out,
            "| {} | {cost} | {hp} | {} | {:?} | {:?} | {} | {} |",
            u.id,
            u.speed,
            m.domain,
            m.role,
            arms(&d, item, false),
            arms(&d, item, true)
        )?;
    }
    out.push_str("\n## Buildings\n\n| ID | Cost | HP | Footprint | Power produced/consumed | Role | Capturable |\n|---|---:|---:|---|---|---|---|\n");
    for b in d.buildings() {
        let k = d
            .building_kind(&b.id)
            .ok_or("catalogue building identity")?;
        let m = d
            .metadata(ProductionItem::Building(k))
            .ok_or("catalogue building metadata")?;
        let hp = d
            .building_combat(k)
            .ok_or("catalogue building combat")?
            .hit_points;
        writeln!(
            &mut out,
            "| {} | {} | {hp} | {}×{} | {}/{} | {:?} | {} |",
            b.id,
            b.production.cost,
            b.width,
            b.height,
            b.power_produced,
            b.power_consumed,
            m.role,
            m.capturable
        )?;
    }
    out.push_str("\n## Weapons\n\n| ID | Damage | Range | Reload | Burst | Projectile speed | Warhead |\n|---|---:|---:|---:|---:|---:|---|\n");
    for w in d.weapons() {
        let wh = d.warhead(w.warhead).ok_or("catalogue warhead")?;
        writeln!(
            &mut out,
            "| {} | {} | {} | {} | {} | {} | {} |",
            w.id, w.damage, w.range, w.reload, w.burst, w.projectile_speed, wh.id
        )?;
    }
    out.push_str("\n## Warheads\n\n| ID | Spread | Edge percent | Wall | Wood | Verses in loaded armour order |\n|---|---:|---:|---|---|---|\n");
    for w in d.warheads() {
        let verses = d
            .armour_classes()
            .iter()
            .zip(&w.versus)
            .map(|(a, v)| format!("{a}:{v}"))
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(
            &mut out,
            "| {} | {} | {} | {} | {} | {verses} |",
            w.id, w.cell_spread, w.percent_at_max, w.wall, w.wood
        )?;
    }
    setup_catalogue(&root, &d, &mut out)?;
    print!("{out}");
    Ok(())
}

fn setup_catalogue(
    root: &std::path::Path,
    d: &Definitions,
    out: &mut String,
) -> Result<(), Box<dyn Error>> {
    let data = root.join("assets/data");
    let skirmish = sim::load_skirmish(data.join("skirmish.ron"), d)?;
    let ai = sim::load_ai(data.join("ai.ron"), d)?;
    sim::check_ai_factions(data.join("ai.ron"), &ai, &skirmish, d)?;
    writeln!(
        out,
        "\n## Actual loader counts\n\nUnits: {}; buildings: {}; weapons: {}; warheads: {}; armour classes: {}; skirmish countries: {}; maps: {}; raw AI plans: {}; difficulties: {}.\n\nRaw plans can include compatibility plans; country plans below use the actual plan_for selection and filtering. Map sizes and starts are the filed loader values; MAP GROWTH OFF limits players to the filed starts and MAP GROWTH ON derives starts for up to ten. This catalogue does not execute matches or certify yard exits.",
        d.units().len(),
        d.buildings().len(),
        d.weapons().len(),
        d.warheads().len(),
        d.armour_classes().len(),
        skirmish.factions.len(),
        skirmish.maps.len(),
        ai.plans.len(),
        ai.difficulties.len()
    )?;
    out.push_str("\n## Filed maps\n\n| Map ID | Width | Height | Filed start positions | Maximum players without growth |\n|---|---:|---:|---:|---:|\n");
    for spec in &skirmish.maps {
        let map = sim::load_map(root.join("assets").join(sim::map_asset_path(&spec.id)))?;
        writeln!(
            out,
            "| {} | {} | {} | {} | {} |",
            spec.id,
            map.grid.width(),
            map.grid.height(),
            spec.starts.len(),
            spec.starts.len().min(sim::MAX_MATCH_PLAYERS)
        )?;
    }
    let buildings = |values: &[sim::BuildingKind]| -> Result<String, Box<dyn Error>> {
        values
            .iter()
            .map(|kind| {
                d.building(*kind)
                    .map(|value| value.id.clone())
                    .ok_or_else(|| "catalogue plan building identity".into())
            })
            .collect::<Result<Vec<_>, Box<dyn Error>>>()
            .map(|values| values.join(", "))
    };
    let units = |values: &[sim::UnitKind]| -> Result<String, Box<dyn Error>> {
        values
            .iter()
            .map(|kind| {
                d.unit(*kind)
                    .map(|value| value.id.clone())
                    .ok_or_else(|| "catalogue plan unit identity".into())
            })
            .collect::<Result<Vec<_>, Box<dyn Error>>>()
            .map(|values| values.join(", "))
    };
    out.push_str("\n## Raw AI plan catalogue\n\n| Index | Side | Country ID | Power | Harvester | Build order | Army order | Defences | Support |\n|---|---|---|---|---|---|---|---|---|\n");
    for (index, plan) in ai.plans.iter().enumerate() {
        writeln!(
            out,
            "| {index} | {:?} | {:?} | {} | {} | {} | {} | {} | {} |",
            plan.side,
            plan.country,
            buildings(&[plan.power])?,
            units(&[plan.harvester])?,
            buildings(&plan.build_order)?,
            units(&plan.army)?,
            buildings(&plan.defences)?,
            units(&plan.support)?
        )?;
    }
    out.push_str("\n## Actual resolved country plans\n\n| Country | Side | Derived roster size | Power | Harvester | Build order | Army order | Tier reserves | Advanced tech level |\n|---|---|---:|---|---|---|---|---|---:|\n");
    for faction in &skirmish.factions {
        let plan = ai
            .plan_for(faction)
            .ok_or("catalogue resolved country plan")?;
        writeln!(
            out,
            "| {} | {:?} | {} | {} | {} | {} | {} | {:?} | {} |",
            faction.id,
            faction.side,
            faction.roster.len(),
            buildings(&[plan.power])?,
            units(&[plan.harvester])?,
            buildings(&plan.build_order)?,
            units(&plan.army)?,
            plan.tier_reserves,
            plan.advanced_tech_level
        )?;
    }
    out.push_str("\n## Actual AI difficulties\n\n| ID | Think interval | Max army | Wave size | First wave | Wave patience | Defence radius |\n|---|---:|---:|---:|---:|---:|---:|\n");
    for difficulty in &ai.difficulties {
        writeln!(
            out,
            "| {} | {} | {} | {} | {} | {} | {} |",
            difficulty.id,
            difficulty.think_interval,
            difficulty.max_army,
            difficulty.wave_size,
            difficulty.first_wave,
            difficulty.wave_patience,
            difficulty.defence_radius
        )?;
    }
    Ok(())
}
